/**
 * Shell completions for a command made of subcommands (`defineCommands`): the command words first, then the options
 * (and positional choices) of the command they lead to, at any depth.
 *
 * @remarks
 * Each shell gets a small function that reads the words typed so far, keeps those that make a known path of commands
 * (`note add`), and offers what that path takes. A script without subcommands keeps the completions of `docs.ts`.
 *
 * @module
 */
import type { Shell } from "./docs.types.ts";
import type { HelpSource } from "./help.types.ts";

/** One place in the tree: its path of command words and what can be typed there. */
type CompletionPlace = {
  /** The command words leading to it, joined by spaces; empty for the top. */
  readonly path: string;
  /** Its commands' words; none for a command that runs. */
  readonly commands: readonly string[];
  /** The options it accepts, its own and the inherited ones. */
  readonly options: HelpSource["options"];
  /** The choices of its positionals. */
  readonly choices: readonly string[];
  /** Everything it offers as words: its commands, its options' names, its positionals' choices. */
  readonly words: readonly string[];
};

/** Quotes text for a single-quoted shell string. */
const quote = (text: string): string => `'${text.replaceAll("'", `'\\''`)}'`;

/** A shell function name from a command name. */
const functionName = (command: string): string => `_${command.replace(/[^A-Za-z0-9_]/g, "_")}`;

/** The option words of a place: long names and short aliases, its own and the inherited ones. */
const optionWords = (source: HelpSource): string[] =>
  Object.entries({ ...source.inherited, ...source.options }).flatMap(([name, option]) =>
    option.short ? [`--${name}`, `-${option.short}`] : [`--${name}`]
  );

/**
 * Every place of a tree, the top first.
 *
 * @param source - The tree's top.
 * @param path - The command words leading to it.
 */
const placesOf = (source: HelpSource, path: readonly string[] = []): CompletionPlace[] => {
  const commands = (source.commands ?? []).map((command) => command.name);
  const choices = (source.positionals ?? []).flatMap((positional) => positional.choices ?? []);
  const place: CompletionPlace = {
    path: path.join(" "),
    commands,
    options: { ...source.inherited, ...source.options },
    choices,
    words: [...commands, ...optionWords(source), ...choices]
  };
  return [place, ...(source.commands ?? []).flatMap((command) => placesOf(command, [...path, command.name]))];
};

/** bash: the path of the words typed so far, then the words of that place. */
const bashTree = (places: readonly CompletionPlace[], command: string): string => {
  const fn = functionName(command);
  const known = places.filter((place) => place.path !== "").map((place) => quote(` ${place.path}`));
  return [
    `# bash completion for ${command} (generated by @ensiria/cli-kit)`,
    `${fn}() {`,
    // biome-ignore lint/suspicious/noTemplateCurlyInString: bash parameter expansion, not a template
    '  local cur="${COMP_WORDS[COMP_CWORD]}" path="" word index words=""',
    "  for ((index = 1; index < COMP_CWORD; index++)); do",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: bash parameter expansion, not a template
    '    word="${COMP_WORDS[index]}"',
    '    case "$word" in -*) continue ;; esac',
    `    case "$path $word" in ${known.join("|")}) path="$path $word" ;; esac`,
    "  done",
    '  case "$path" in',
    ...places.map(
      (place) =>
        `    ${quote(place.path === "" ? "" : ` ${place.path}`)}) words=${quote(place.words.join(" "))} ;;`
    ),
    "  esac",
    '  COMPREPLY=($(compgen -W "$words" -- "$cur"))',
    "}",
    `complete -F ${fn} ${command}`,
    ""
  ].join("\n");
};

/** zsh: the same walk over `$words`, offering the place's words with `compadd`. */
const zshTree = (places: readonly CompletionPlace[], command: string): string => {
  const fn = functionName(command);
  const known = places.filter((place) => place.path !== "").map((place) => quote(` ${place.path}`));
  return [
    `#compdef ${command}`,
    `# zsh completion for ${command} (generated by @ensiria/cli-kit)`,
    `${fn}() {`,
    '  local path="" word index',
    "  local -a offered",
    "  for ((index = 2; index < CURRENT; index++)); do",
    // biome-ignore lint/suspicious/noTemplateCurlyInString: zsh parameter expansion, not a template
    '    word="${words[index]}"',
    '    [[ "$word" == -* ]] && continue',
    `    case "$path $word" in ${known.join("|")}) path="$path $word" ;; esac`,
    "  done",
    '  case "$path" in',
    ...places.map(
      (place) =>
        `    ${quote(place.path === "" ? "" : ` ${place.path}`)}) offered=(${place.words.map(quote).join(" ")}) ;;`
    ),
    "  esac",
    "  compadd -- $offered",
    "}",
    `${fn} "$@"`,
    ""
  ].join("\n");
};

/** fish: a function that prints the path typed so far; per place, its command words and one line per option. */
const fishTree = (places: readonly CompletionPlace[], command: string): string => {
  const fn = `__${functionName(command).slice(1)}_path`;
  const known = places.filter((place) => place.path !== "").map((place) => quote(place.path));
  const condition = (place: CompletionPlace): string =>
    `-n ${quote(`test "(${fn})" = ${quote(place.path)}`)}`;
  const lines = places.flatMap((place) => {
    const words = [...place.commands, ...place.choices];
    const options = Object.entries(place.options).map(([name, option]) => {
      const parts = [`complete -c ${command}`, condition(place), `-l ${name}`];
      if (option.short) parts.push(`-s ${option.short}`);
      if (option.type === "string")
        parts.push(option.choices ? `-x -a ${quote(option.choices.join(" "))}` : "-r");
      parts.push(`-d ${quote(option.description)}`);
      return parts.join(" ");
    });
    return [
      ...(words.length > 0
        ? [`complete -c ${command} -f ${condition(place)} -a ${quote(words.join(" "))}`]
        : []),
      ...options
    ];
  });
  return [
    `# fish completion for ${command} (generated by @ensiria/cli-kit)`,
    `function ${fn}`,
    "    set -l path",
    "    for word in (commandline -opc)[2..-1]",
    "        string match -q -- '-*' $word; and continue",
    "        set -l next (string join ' ' $path $word)",
    `        contains -- $next ${known.join(" ")}; and set path $path $word`,
    "    end",
    "    string join ' ' $path",
    "end",
    ...lines,
    ""
  ].join("\n");
};

/** The writer for each shell. */
const TREE_COMPLETIONS: Readonly<
  Record<Shell, (places: readonly CompletionPlace[], command: string) => string>
> = {
  bash: bashTree,
  zsh: zshTree,
  fish: fishTree
};

/**
 * Completions for a command made of subcommands.
 *
 * @param source - The tree's top (what `defineCommands` gives as `source`).
 * @param shell - Which shell.
 * @param command - The name the command is installed as.
 * @returns The completion script.
 */
export const formatTreeCompletion = (source: HelpSource, shell: Shell, command: string): string =>
  TREE_COMPLETIONS[shell](placesOf(source), command);
